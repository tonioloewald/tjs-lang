/**
 * Generates `src/lang/prelude.generated.js`, the shared prelude `tjs-lang/prelude` ships
 * (#3594): the emitter's own inline runtime with every feature on, wrapped in a factory so each
 * module that imports it gets its own instance. ONE source: the text comes from
 * `fullPrelude()`, the same code path that writes every inline prelude.
 *
 * `render()` is pure; the write runs only as a script (`bun run build:prelude`).
 * `src/lang/prelude.test.ts` fails when the committed file differs from `render()`.
 */
import { fullPrelude } from '../src/lang/emitters/js'

export function render(): string {
  const { inline, exports, hash } = fullPrelude()
  return `// GENERATED by \`bun run build:prelude\` (scripts/build-prelude.ts) from the emitter's
// inline runtime with every feature on. Do not edit: src/lang/prelude.test.ts fails on drift.
//
// Emitted with \`prelude: 'import'\`, a module calls createPrelude(<hash of the code it was
// compiled against>) and gets its OWN instance: the code exists once in a bundle, the state
// (the projection table \`extend\` writes, the call-stack ring) stays per module.
/* eslint-disable */
// @ts-nocheck
export const PRELUDE_HASH = '${hash}'

export function createPrelude(hash) {
  if (hash !== PRELUDE_HASH)
    throw new Error(
      'tjs-lang/prelude: this module was compiled against prelude ' + hash +
        ', but the installed tjs-lang provides ' + PRELUDE_HASH +
        '. Rebuild it with the installed tjs-lang, or emit it with prelude: "inline".'
    )
${inline}return {${exports.join(',')}};
}
`
}

if (import.meta.main) {
  const path = new URL('../src/lang/prelude.generated.js', import.meta.url)
  await Bun.write(path, render())
  console.log(`wrote ${path.pathname}`)
}
